include(joinpath(@__DIR__, "paths.jl"))
include(joinpath(@__DIR__, "read_results.jl"))
using Printf

const P   = read_final_calibration(CAL_PATHS.out_calibration).params
const RES = read_results_toml(CAL_PATHS.out_calibration)
const KN  = get(RES, "zeta_knots", Dict{String,Any}())
const KNOTS = haskey(KN, "ln_rs")
const KNOT_YEARS = [1950, 1960, 1970, 1980, 1990, 2000, 2010, 2023]   # ZETA_KNOT_YEARS in smm_ge_unified.jl

const M_GOODS = "Goods LP trend and patent stock"
const ROWS = [
    ("\$\\kappa_m\$",         "Goods variety-expansion parameter",         "kappa_m",  M_GOODS),
    ("\$\\kappa_{rs}\$",      "RI-Serv. variety-expansion parameter",      "kappa_rs", "RI-Serv. LP trend"),
    ("\$\\kappa_{ns}\$",      "NRI-Serv. variety-expansion parameter",     "kappa_ns", "NRI-Serv. LP trend"),
    ("\$\\sigma\$",           "Elasticity of substitution across sectors", "sigma",    "Goods and RI-Serv. VA shares"),
    ("\$\\theta_m\$",         "Goods consumption weight",                  "theta_m",  "Goods VA share, 1950"),
    ("\$\\theta_{rs}\$",      "RI-Serv. consumption weight",               "theta_rs", "RI-Serv. VA share, 1950"),
    ("\$\\eta_m\$",           "Goods Engel parameter",                     "eta_m",    "Goods VA share"),
    ("\$\\eta_{rs}\$",        "RI-Serv. Engel parameter",                  "eta_rs",   "RI-Serv. VA share"),
    ("\$\\zeta_m(1950)\$",    "Initial Goods research productivity",       "zeta0_m",  M_GOODS),
    ("\$g_{\\zeta,m}\$",      "Goods research productivity growth",        "gzeta_m",  M_GOODS),
]
const ROWS_SERVICES = [   # constant services growth only
    ("\$\\zeta_{rs}(1950)\$", "Initial RI-Serv. research productivity",    "zeta0_rs", "RI-Serv. R\\&D-worker share"),
    ("\$\\zeta_{ns}(1950)\$", "Initial NRI-Serv. research productivity",   "zeta0_ns", "NRI-Serv. R\\&D-worker share"),
    ("\$g_{\\zeta,rs}\$",     "RI-Serv. research productivity growth",     "gzeta_rs", "RI-Serv. R\\&D-worker share"),
    ("\$g_{\\zeta,ns}\$",     "NRI-Serv. research productivity growth",    "gzeta_ns", "NRI-Serv. R\\&D-worker share"),
]
const SIGMA_LB = abs(P["sigma"] - 0.005) < 1e-9
nk = length(KNOT_YEARS)
KNOTS && (length(KN["ln_rs"]) == nk || error("expected $nk knots, found $(length(KN["ln_rs"]))"))

io = IOBuffer()
println(io, "% Auto-generated by calibration_table.jl from final_calibration.txt — do not edit by hand.")
println(io, "% Requires: booktabs, threeparttable, siunitx, ragged2e, graphicx")
println(io, "\\begin{table}[htbp]")
println(io, "  \\centering")
println(io, "  \\caption{Internally Calibrated Parameters}")
println(io, "  \\label{tab:internally_calibrated_parameters}")
println(io, "  \\begin{threeparttable}")
println(io, "  \\centering")
println(io, "  \\resizebox{\\textwidth}{!}{%")
println(io, "  \\begin{tabular}{l l S[table-format=-1.4] l}")
println(io, "    \\toprule")
println(io, "    \\multicolumn{4}{l}{\\textit{Panel A. Parameters}} \\\\")
println(io, "    {Parameter} & {Interpretation} & {Value} & {Most informative moment} \\\\")
println(io, "    \\midrule")
for (sym, interp, key, moment) in (KNOTS ? ROWS : vcat(ROWS, ROWS_SERVICES))
    haskey(P, key) || error("final_calibration.txt has no $key")
    @printf(io, "    %s & %s & %.4f & %s \\\\\n", sym, interp, P[key], moment)
end
println(io, "    \\bottomrule")
println(io, "  \\end{tabular}}")
if KNOTS
    println(io, "")
    println(io, "  \\vspace{0.6em}")
    println(io, "  \\resizebox{\\textwidth}{!}{%")
    println(io, "  \\begin{tabular}{l", "c"^nk, "}")
    println(io, "    \\toprule")
    println(io, "    \\multicolumn{$(nk+1)}{l}{\\textit{Panel B. Services research productivity \$\\zeta_j(t_k)\$ at the knots}} \\\\")
    println(io, "    Knot & ", join(string.(KNOT_YEARS), " & "), " \\\\")
    println(io, "    \\midrule")
    for (label, key) in (("RI-Serv.", "ln_rs"), ("NRI-Serv.", "ln_ns"))
        println(io, "    ", label, " & ", join([@sprintf("%.3f", exp(x)) for x in KN[key]], " & "), " \\\\")
    end
    println(io, "    \\bottomrule")
    println(io, "  \\end{tabular}}")
end
println(io, "  \\end{threeparttable}")
println(io, "  \\begin{minipage}{\\textwidth}")
println(io, "    \\footnotesize")
println(io, "    \\RaggedRight")
println(io, "    \\noindent\\textit{Notes:} The table reports internally calibrated parameters. Parameters are calibrated")
println(io, "    jointly using the full set of calibration targets; the last column of Panel A reports the moment that is")
println(io, "    most informative for each parameter. LP denotes labor productivity and VA value added; all targets are")
println(io, "    paths over 1950--2023 unless a year is given. The consumption weights \$\\theta_m\$ and \$\\theta_{rs}\$ are")
println(io, "    disciplined by 1950 value-added shares, with \$\\theta_{ns} = 1 - \\theta_m - \\theta_{rs}\$, and the")
println(io, "    income-elasticity parameter of NRI-Services is normalized to \$\\eta_{ns} = 1\$.",
            SIGMA_LB ? " The elasticity \$\\sigma\$ is at its lower bound of 0.005." : "")
println(io, "    Goods research productivity is \$\\zeta_m(t) = \\zeta_m(1950)e^{g_{\\zeta,m}(t-1950)}\$.",
            KNOTS ? " In the two service sectors, the knots in Panel B are disciplined by the sectoral R\\&D-worker share paths; \$\\ln \\zeta_j(t)\$ is linear between knots and grows at its 2010--2023 rate after 2023." :
                    " In the two service sectors research productivity grows at a constant rate, disciplined by the sectoral R\\&D-worker share paths.")
println(io, "    Labor productivity targets are the smoothing-spline trends of log labor productivity: the Goods parameters")
println(io, "    fit the annual trend path, and \$\\kappa_{rs}\$ and \$\\kappa_{ns}\$ equate the model and trend slopes of")
println(io, "    cumulative log productivity growth since 1950.")
println(io, "  \\end{minipage}")
println(io, "\\end{table}")

const OUT = joinpath(CAL_PATHS.out_calibration, "Table_2.tex")
open(f -> write(f, String(take!(io))), OUT, "w")
println("Wrote ", OUT)
