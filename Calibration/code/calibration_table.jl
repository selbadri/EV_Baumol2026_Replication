 Inputs:  output/calibration/final_calibration.txt, calibration_results.toml
 Outputs: output/calibration/Table_2.tex
 ------------------------------------------------------------------------------------------
 Notes:
 Panel A lists the scalar parameters. Panel B lists services research productivity at the
 knots (BLOCKB_MODE=knots, the baseline). Under constant services growth (BLOCKB_MODE=legacy)
 Panel B is replaced by the services zeta_j(1950) and g_zeta,j rows in Panel A.
